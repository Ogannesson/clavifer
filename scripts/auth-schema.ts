// Derive the pinned auth library's tables; generated SQL is reviewed and committed. They open the
// initial migration: everything after its first blank line is the service's own schema, kept as it is.
// The file holds no comment before a statement, since wrangler sends such comments to D1 with it.
import { getAuthTables } from 'better-auth/db';
import { readFile, writeFile } from 'node:fs/promises';
import { authPlugins } from '../packages/auth/policy';
const tables = getAuthTables({
  plugins: authPlugins('http://localhost:8787'),
  rateLimit: { storage: 'database' },
});
let ts =
  "// Generated by scripts/auth-schema.ts from locked Better Auth dependencies.\nimport { sqliteTable, text, integer, real, index } from 'drizzle-orm/sqlite-core';\n";
let sql = '';
const q = (s: string) => '"' + s.replaceAll('"', '""') + '"';
for (const [name, table] of Object.entries(tables)) {
  const fields = { id: { type: 'string', required: true, unique: true }, ...table.fields };
  ts += `export const ${name} = sqliteTable(${JSON.stringify(name)}, {\n`;
  const cols: string[] = [];
  for (const [field, f] of Object.entries(fields)) {
    let expression = `text(${JSON.stringify(field)})`,
      kind = 'TEXT';
    if (f.type === 'date') {
      expression = `integer(${JSON.stringify(field)}, {mode:'timestamp_ms'})`;
      kind = 'INTEGER';
    }
    if (f.type === 'boolean') {
      expression = `integer(${JSON.stringify(field)}, {mode:'boolean'})`;
      kind = 'INTEGER';
    }
    if (f.type === 'number') {
      expression = `real(${JSON.stringify(field)})`;
      kind = 'REAL';
    }
    if (field === 'id') expression += '.primaryKey()';
    else if (f.unique) expression += '.unique()';
    if (f.required) expression += '.notNull()';
    ts += `  ${field}: ${expression},\n`;
    cols.push(
      `${q(field)} ${kind}${field === 'id' ? ' PRIMARY KEY' : f.unique ? ' UNIQUE' : ''}${f.required ? ' NOT NULL' : ''}`,
    );
  }
  ts += '});\n';
  sql += `CREATE TABLE ${q(name)} (\n  ${cols.join(',\n  ')}\n);\n`;
  for (const [field, f] of Object.entries(table.fields)) {
    if (f.references || f.index) sql += `CREATE INDEX ${q(`${name}_${field}_idx`)} ON ${q(name)}(${q(field)});\n`;
  }
}
const migration = 'migrations/0001_initial.sql';
const own = await readFile(migration, 'utf8');
await writeFile('packages/auth/schema.ts', ts);
await writeFile(migration, sql + own.slice(own.indexOf('\n\n') + 1));
